import * as React from "react";

/**
 * Material Symbols — the icon set at fonts.google.com/icons, inlined.
 *
 * Every export is named for its entry in that catalog: `KeyboardArrowDown` is
 * `keyboard_arrow_down`, `OpenInNew` is `open_in_new`. Paste the name back
 * into the site with underscores and you land on the glyph. That is the point
 * of the naming — adding an icon means looking it up there first, and a name
 * you cannot find on the site is a name that should not be in this file.
 *
 * Add a new one by pulling the real path data rather than drawing it:
 *
 *   https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/<name>/default/24px.svg
 *
 * Hand-drawn SVG belongs in `icons.tsx`, and only for marks the catalog does
 * not have — brand marks like the Gemini spark, mostly.
 *
 * All of these are the outlined style on the 960 grid, filled with
 * `currentColor`, so they take their colour from whatever `text-cm-*` token
 * is in scope and size from `size-*` like any other box. The 24px default
 * matters: an `<svg>` with no intrinsic size falls back to 300x150, so a
 * caller that forgets a size class gets an icon rather than a billboard.
 */

export type IconProps = React.SVGProps<SVGSVGElement>;

/** For props that take an icon rather than render one. */
export type MaterialSymbol = React.ComponentType<IconProps>;

function symbol(displayName: string, d: string) {
  const Icon = (props: IconProps) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 -960 960 960"
      width="24"
      height="24"
      fill="currentColor"
      {...props}
    >
      <path d={d} />
    </svg>
  );
  Icon.displayName = displayName;
  return Icon;
}

/**
 * The same glyph with and without its counter filled in. `filled` is the fill
 * axis on fonts.google.com/icons, not a colour: the inner mark winds against
 * the outer shape, so it becomes a hole and the background shows through it.
 * That is how a severity icon reads as two-tone without being two elements.
 */
function filledSymbol(displayName: string, outlined: string, filled: string) {
  const Icon = ({
    filled: isFilled = false,
    ...props
  }: IconProps & { filled?: boolean }) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 -960 960 960"
      width="24"
      height="24"
      fill="currentColor"
      {...props}
    >
      <path d={isFilled ? filled : outlined} />
    </svg>
  );
  Icon.displayName = displayName;
  return Icon;
}

/**
 * The same glyph at two points on the weight axis. Material Symbols has no
 * stroke to thicken — a heavier mark is a different path, so `weight={700}`
 * is what replaces a `stroke-[3]` on a small tick.
 */
function weightedSymbol(displayName: string, d400: string, d700: string) {
  const Icon = ({
    weight = 400,
    ...props
  }: IconProps & { weight?: 400 | 700 }) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 -960 960 960"
      width="24"
      height="24"
      fill="currentColor"
      {...props}
    >
      <path d={weight === 700 ? d700 : d400} />
    </svg>
  );
  Icon.displayName = displayName;
  return Icon;
}

